SUBS_PER_PERSONA = 10


def sub_uid(parent_uid: int, sub_i: int) -> int:
    """父人格 9001 的子人格 9101–9110；9010 的子人格 10001–10010。"""
    idx = int(parent_uid) - 9000
    return 9000 + idx * 100 + int(sub_i)


def iter_grid() -> list[tuple[str, int, int, int, str]]:
    """(人格名, 父uid, 子序號, 子uid, 查股代號) ×100"""
    out: list[tuple[str, int, int, int, str]] = []
    for name, parent_uid, codes in PERSONAS_10:
        for sub_i in range(1, SUBS_PER_PERSONA + 1):
            uid = sub_uid(parent_uid, sub_i)
            code = codes[(sub_i - 1) % len(codes)]
            out.append((name, parent_uid, sub_i, uid, code))
    return out


def all_sub_uids() -> list[int]:
    return [row[3] for row in iter_grid()]
