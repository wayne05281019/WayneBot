def match_methods(ask: str, *, limit: int = 3) -> List[Tuple[str, str]]:
    q = ask or ""
    hits: List[Tuple[str, str]] = []
    for pat, title, body in _METHODS:
        if pat.search(q):
            hits.append((title, body))
        if len(hits) >= limit:
            break
    return hits


def format_methods_html(ask: str) -> str:
    hits = match_methods(ask)
    chunks: List[str] = []
    try:
        from biaoke_why import format_why_html, is_why_query

        why = format_why_html(ask)
        if why:
            chunks.append(why)
        elif is_why_query(ask) and not hits:
            chunks.append(html_escape("這句對不到已建檔的點位／改口鏈，不准編。"))
    except Exception:
        pass
    chunks.extend(html_escape(body) for _title, body in hits)
    try:
        from biaoke_witness import format_witness_html, is_witness_query

        if is_witness_query(ask):
            chunks.append(format_witness_html(ask))
    except Exception:
        pass
    return "\n".join(chunks)


def is_method_query(ask: str) -> bool:
    q = (ask or "").strip()
    if not q:
        return False
    if match_methods(q, limit=1):
        return True
    try:
        from biaoke_why import is_why_query, lookup

        return bool(is_why_query(q) and lookup(q))
    except Exception:
        return False


def follow_up_ask(ask: str, history: Optional[Sequence[Any]] = None) -> str:
    """『那呢／那一檔』接上一句題目，才像對話不是考卷。"""
    q = (ask or "").strip()
    if not q or not history:
        return q
    if not re.match(
        r"^(那|這個|剛剛|同上|繼續|所以|然後|對啊|對阿|嗯|喔|那呢|"
        r"還能|會嗎|真的|這樣|對吧|呢$)",
        q,
    ):
        return q
    if len(q) >= 24:
        return q
    last = ""
    for item in reversed(list(history)):
        if isinstance(item, dict):
            last = str(item.get("ask") or "")
        elif isinstance(item, (list, tuple)) and item:
            last = str(item[0])
        else:
            last = str(item)
        if last.strip():
            break
    if not last:
        return q
    return f"{last} {q}".strip()


