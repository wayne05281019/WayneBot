def line_for(sid: str) -> str:
    """問到這檔才貼已對過的圖文。沒走完的後面不准編。"""
    rows = _BY_SID.get(str(sid or "").strip()) or []
    if not rows:
        return ""
    bits = [HOW, f"時間軸走到 {SLICE_STOP}。"]
    for e in rows:
        bits.append(
            f"{e['date']} {e['name']} {e['sid']}。"
            f"{e['why']}{e['official']}後證：{e['later']}{e['verdict']}"
        )
    bits.append("不是 4/16 長抱。不是買訊。")
    return "".join(bits)


